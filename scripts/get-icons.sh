#!/usr/bin/env bash
# Downloads Google's Material Symbols and writes js/icons-material.js with only the icons Gradis uses.
# Run it in Termux, from the root of the web app folder (the one that has index.html; if there is a www/ folder next to it, it is updated too):   bash scripts/get-icons.sh
# Needs internet once. Afterwards the icons are part of the app and work offline.
set -e
cd "$(dirname "$0")/.."
STYLE="${STYLE:-rounded}"            # rounded | outlined | sharp
WEIGHT="${WEIGHT:-600}"              # 100..700 (600 matches Gradis' chunky look)
NAMES="close arrow_back arrow_forward schedule menu_book home bar_chart search settings ios_share trending_up check keyboard_arrow_up keyboard_arrow_down drag_indicator lightbulb"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
if [ -n "$PKG_TGZ" ]; then cp "$PKG_TGZ" "$W/p.tgz"; else
  echo "Downloading Material Symbols (weight $WEIGHT)…"
  (cd "$W" && npm pack "@material-symbols/svg-$WEIGHT" --silent >/dev/null && mv ./*.tgz p.tgz)
fi
mkdir "$W/x" && tar -xzf "$W/p.tgz" -C "$W/x"
node - "$W/x" "$STYLE" $NAMES <<'JS'
const fs=require("fs"),path=require("path");
const [root,style,...names]=process.argv.slice(2);
const files=[];(function walk(d){for(const f of fs.readdirSync(d,{withFileTypes:true})){const p=path.join(d,f.name);f.isDirectory()?walk(p):f.name.endsWith(".svg")&&files.push(p)}})(root);
const out={},missing=[];
for(const n of names){
  const f=files.find(p=>path.basename(p)===n+".svg"&&p.split(path.sep).includes(style));
  if(!f){missing.push(n);continue}
  const s=fs.readFileSync(f,"utf8");
  const vb=(s.match(/viewBox="([^"]+)"/)||[])[1];
  const d=[...s.matchAll(/\sd="([^"]+)"/g)].map(m=>m[1]).join("");
  if(vb!=="0 -960 960 960"||!d){missing.push(n+" (unexpected format)");continue}
  out[n]=d;
}
if(missing.length){console.error("Could not find: "+missing.join(", "));process.exit(1)}
fs.writeFileSync("js/icons-material.js","/* Google Material Symbols ("+style+"), generated by scripts/get-icons.sh. Licence: Apache 2.0. */\nconst MAT="+JSON.stringify(out)+";\n");
console.log("Wrote js/icons-material.js with "+names.length+" icons");
JS
[ -d www/js ] && cp js/icons-material.js www/js/icons-material.js && echo "Copied to www/js too."
echo "Done. Upload js/icons-material.js (and bump VERSION in sw.js) to publish the new icons."
